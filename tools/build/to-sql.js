// Turn the compiled content JSON into SQL for D1.
//
// Emitted as a single idempotent file so a reload is safe: every INSERT is an
// upsert keyed on the natural primary key, and nothing here touches `attempts`,
// `serves`, `mocks` or `gaps`. Reloading content must never disturb evidence.
//
// The one derivation done here: items carry a topic ("2.5") but no unit, and the
// readiness engine needs per-unit breakdowns. Unit comes from the topics table
// rather than from parsing the topic id, so a topic whose unit is not what its
// prefix suggests still lands correctly.

import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/** SQL string literal, or NULL. Doubles embedded quotes; never interpolates raw. */
export function lit(v) {
  if (v == null) return 'NULL'
  if (typeof v === 'number') return String(v)
  if (typeof v === 'boolean') return v ? '1' : '0'
  return `'${String(v).replace(/'/g, "''")}'`
}

/** Build a topic -> unit map so items can be tagged with the unit they belong to. */
export function unitIndex(topics) {
  return new Map(topics.map((t) => [`${t.subject}:${t.id}`, t.unit]))
}

export function itemRows(items, units) {
  return items.map((it) => {
    const unit = units.get(`${it.subject}:${it.topic}`) ?? null
    return [
      lit(it.id), lit(it.subject), lit(it.topic), lit(unit), lit(it.practice ?? null),
      lit(it.kind), lit(it.stem),
      lit(it.options ? JSON.stringify(it.options) : null),
      lit(it.answer ?? null),
      lit(it.answer_variants ? JSON.stringify(it.answer_variants) : null),
      lit(it.explanation ?? null),
      lit(it.rubric ? JSON.stringify(it.rubric) : null),
      lit(it.difficulty ?? null),
      lit(it.calc_allowed ?? null),
    ]
  })
}

export function topicRows(topics) {
  return topics.map((t) => [
    lit(t.id), lit(t.subject), lit(t.name ?? null), lit(t.unit ?? null), lit(t.ek ?? null),
    lit(t.exam_weight_low ?? null), lit(t.exam_weight_high ?? null),
    lit(t.tested_on_exam === false ? 0 : 1),
  ])
}

export function teachingRows(teaching) {
  return teaching.map((t) => [
    lit(t.topic), lit(t.subject), lit(t.plain_idea ?? null),
    lit(t.worked_example ?? null), lit(t.common_mistake ?? null), lit(t.source_file ?? null),
  ])
}

/** Chunk rows into multi-value INSERTs; D1 rejects very large single statements. */
function insertStatements(table, columns, rows, chunk = 40) {
  const out = []
  for (let i = 0; i < rows.length; i += chunk) {
    const values = rows.slice(i, i + chunk).map((r) => `  (${r.join(', ')})`).join(',\n')
    out.push(`INSERT OR REPLACE INTO ${table} (${columns.join(', ')}) VALUES\n${values};`)
  }
  return out
}

export function buildSql({ items, topics, teaching, schema }) {
  const units = unitIndex(topics)
  const parts = [
    '-- Generated by tools/build/to-sql.js. Do not edit by hand.',
    '-- Idempotent: reloading content never touches attempts, serves, mocks or gaps.',
    '',
    schema,
    '',
    ...insertStatements(
      'topics',
      ['id', 'subject', 'name', 'unit', 'ek', 'exam_weight_low', 'exam_weight_high', 'tested_on_exam'],
      topicRows(topics),
    ),
    '',
    ...insertStatements(
      'items',
      ['id', 'subject', 'topic', 'unit', 'practice', 'kind', 'stem', 'options_json',
        'answer', 'answer_variants_json', 'explanation', 'rubric_json', 'difficulty', 'calc_allowed'],
      itemRows(items, units),
    ),
    '',
    ...insertStatements(
      'teaching',
      ['topic', 'subject', 'plain_idea', 'worked_example', 'common_mistake', 'source_file'],
      teachingRows(teaching),
    ),
    '',
  ]
  return parts.join('\n')
}

function main() {
  const root = process.cwd()
  const read = (f) => JSON.parse(readFileSync(join(root, 'content', f), 'utf8'))
  const items = read('items.json')
  const topics = read('topics.json')
  const teaching = read('teaching.json')
  const schema = readFileSync(join(root, 'worker', 'schema.sql'), 'utf8')

  const units = unitIndex(topics)
  const orphans = items.filter((it) => !units.has(`${it.subject}:${it.topic}`))
  if (orphans.length) {
    // An item whose topic has no row would be invisible to every per-unit floor,
    // so it must be a hard error rather than a NULL unit.
    console.error(`ERROR: ${orphans.length} item(s) reference a topic with no row:`)
    for (const o of orphans.slice(0, 10)) console.error(`  ${o.id} -> topic ${o.topic}`)
    process.exit(1)
  }

  const sql = buildSql({ items, topics, teaching, schema })
  const out = join(root, 'worker', 'seed.sql')
  writeFileSync(out, sql)

  const bySubject = {}
  for (const it of items) bySubject[it.subject] = (bySubject[it.subject] ?? 0) + 1
  console.log(`wrote ${out}`)
  console.log(`  items:    ${items.length} (${Object.entries(bySubject).map(([k, v]) => `${k}=${v}`).join(', ')})`)
  console.log(`  topics:   ${topics.length}`)
  console.log(`  teaching: ${teaching.length}`)
  console.log(`  size:     ${(sql.length / 1024).toFixed(0)} KiB`)
}

if (import.meta.url === `file://${process.argv[1]}`) main()
